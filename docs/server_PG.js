app.get('/api/inquiries', async (req, res) => {
    try {
        const { status, keyword } = req.query;
        let conditions = ["1=1"];
        let params = [];
        let paramIdx = 1;

        if (status && status !== 'ALL') {
            conditions.push(`status = $${paramIdx++}`);
            params.push(status);
        }

        if (keyword && keyword.trim()) {
            conditions.push(`(name ILIKE $${paramIdx} OR phone ILIKE $${paramIdx} OR message ILIKE $${paramIdx})`);
            params.push(`%${keyword.trim()}%`);
            paramIdx++;
        }

        const sql = `
            SELECT 
                id, name, phone, COALESCE(email, '') AS email,
                category, message, status, COALESCE(reply_note, '') AS reply_note,
                created_at
            FROM guest_inquiries
            WHERE ${conditions.join(" AND ")}
            ORDER BY CASE WHEN status = 'PENDING' THEN 0 ELSE 1 END, created_at DESC
        `;

        const { rows } = await pool.query(sql, params);
        res.json({ success: true, data: rows });
    } catch (err) {
        res.status(500).json({ success: false, message: '伺服器讀取異常' });
    }
});

