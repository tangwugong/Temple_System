// 信眾報名登記
app.post('/api/events/register', async (req, res) => {
    const client = await pool.connect();
    try {
        const { eventId, applicantName, contactPhone, category, targetName, seats, offering } = req.body;

        await client.query('BEGIN');

        // 鎖定活動資料防止超額登記
        const evtRes = await client.query('SELECT * FROM temple_events WHERE id = $1 FOR UPDATE', [eventId]);
        const evt = evtRes.rows[0];
        if (!evt) {
            await client.query('ROLLBACK');
            return res.status(404).json({ success: false, message: '找不到該活動' });
        }

        const quotaRes = await client.query(
            "SELECT COALESCE(SUM(seats), 0)::int AS used FROM event_roster WHERE event_id = $1 AND pay_status != 'CANCELLED'",
            [eventId]
        );
        if (quotaRes.rows[0].used + Number(seats) > Number(evt.max_quota)) {
            await client.query('ROLLBACK');
            return res.status(400).json({ success: false, message: '登記席次超過本次法會上限！' });
        }

        const regId = `REG-${Date.now().toString().slice(-6)}`;
        const totalAmount = Number(evt.fee) * Number(seats);

        await client.query(`
            INSERT INTO event_roster (reg_id, event_id, name, phone, category, target_name, seats, amount, offering, pay_status)
            VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9, 'PENDING')
        `, [regId, eventId, applicantName, contactPhone, category, targetName, Number(seats), totalAmount, offering]);

        await client.query('COMMIT');
        res.json({ success: true, message: '報名登記成功！請靜候會計核銷入帳。', regId });
    } catch (e) {
        await client.query('ROLLBACK');
        res.status(500).json({ success: false, message: '報名登記失敗: ' + e.message });
    } finally {
        client.release();
    }
});

