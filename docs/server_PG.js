// 取得家戶與眷屬列表
app.get('/api/households', async (req, res) => {
    try {
        const householdsRes = await pool.query('SELECT * FROM family_household ORDER BY created_at DESC');
        const membersRes = await pool.query('SELECT * FROM believer_member ORDER BY created_at ASC');

        const households = householdsRes.rows;
        const members = membersRes.rows;

        const data = households.map(h => {
            const mList = members.filter(m => m.family_code === h.family_code);
            const headMember = mList.find(m => m.relationship === '戶長') || {};

            return {
                familyCode: h.family_code,
                name: h.head_name,
                phone: h.phone,
                address: h.address,
                birthdate: headMember.birthdate || '',
                zodiac: headMember.zodiac || '',
                idNumber: headMember.id_number || '',
                members: mList.map(m => ({
                    id: m.member_id,
                    name: m.name,
                    relationship: m.relationship,
                    phone: m.phone,
                    birthdate: m.birthdate,
                    zodiac: m.zodiac,
                    idNumber: m.id_number
                }))
            };
        });
        res.json({ success: true, data });
    } catch (err) {
        res.status(500).json({ success: false, message: err.message });
    }
});

