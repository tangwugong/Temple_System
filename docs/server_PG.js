app.get('/api/finance/records', async (req, res) => {
    try {
        const { txType, category, startDate, endDate } = req.query;

        let conditions = ["1=1"];
        let params = [];
        let paramIdx = 1;

        if (txType && txType !== 'ALL') {
            conditions.push(`tx_type = $${paramIdx++}`);
            params.push(txType);
        }

        if (category && category !== 'ALL') {
            conditions.push(`category = $${paramIdx++}`);
            params.push(category);
        }

        if (startDate) {
            conditions.push(`tx_date >= $${paramIdx++}`);
            params.push(startDate);
        }
        if (endDate) {
            conditions.push(`tx_date <= $${paramIdx++}`);
            params.push(endDate);
        }

        const whereSql = conditions.join(" AND ");

        const sql = `
            SELECT 
                id,
                COALESCE(tx_no, '') AS "txNo",
                COALESCE(tx_type, 'INCOME') AS "txType",
                COALESCE(category, '未分類') AS category,
                COALESCE(amount, 0)::float AS amount,
                COALESCE(payment_method, 'CASH') AS "paymentMethod",
                COALESCE(source_module, 'MANUAL') AS "sourceModule",
                COALESCE(payer_name, '無名氏') AS "payerName",
                COALESCE(receipt_no, '') AS "receiptNo",
                COALESCE(handled_by, '會計組') AS "handledBy",
                COALESCE(memo, '') AS memo,
                TO_CHAR(COALESCE(tx_date, CURRENT_DATE), 'YYYY-MM-DD') AS "txDate",
                created_at AS "createdAt"
            FROM finance_records
            WHERE ${whereSql}
            ORDER BY tx_date DESC, id DESC
        `;

        const recordsRes = await pool.query(sql, params);

        const summarySql = `
            SELECT 
                COALESCE(SUM(CASE WHEN tx_type = 'INCOME' THEN amount ELSE 0 END), 0)::float AS "totalIncome",
                COALESCE(SUM(CASE WHEN tx_type = 'EXPENSE' THEN amount ELSE 0 END), 0)::float AS "totalExpense"
            FROM finance_records
            WHERE ${whereSql}
        `;

        const summaryRes = await pool.query(summarySql, params);
        const summaryRow = summaryRes.rows[0] || {};
        const totalIncome = Number(summaryRow.totalIncome) || 0;
        const totalExpense = Number(summaryRow.totalExpense) || 0;

        res.json({
            success: true,
            data: recordsRes.rows,
            summary: {
                totalIncome,
                totalExpense,
                balance: totalIncome - totalExpense
            }
        });
    } catch (err) {
        res.status(500).json({ success: false, message: '讀取財務資料庫失敗: ' + err.message });
    }
});

