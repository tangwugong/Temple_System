app.post('/api/auth/login', async (req, res) => {
    try {
        const { username, password } = req.body;
        if (!username || !password) return res.status(400).json({ success: false, message: '請輸入帳號與密碼' });

        const userRes = await pool.query('SELECT * FROM sys_user WHERE username = $1', [username]);
        const user = userRes.rows[0];

        if (!user || user.password !== password) return res.status(401).json({ success: false, message: '帳號或密碼錯誤' });
        if (user.status !== 'ACTIVE') return res.status(403).json({ success: false, message: '帳號已停用' });

        const token = `TPL-TOKEN-${user.user_id}-${Date.now()}`;
        res.json({
            success: true,
            message: '登入成功',
            token,
            user: {
                userId: user.user_id,
                username: user.username,
                realName: user.real_name,
                real_name: user.real_name,
                role: user.role
            }
        });
    } catch (err) {
        res.status(500).json({ success: false, message: err.message });
    }
});

